const SPACE: f32 = 2.4;
const GAP: f32 = 1.4;

fn glyph(c: char) -> Option<&'static (char, f32, &'static [Stroke])> {
    GLYPHS.iter().find(|g| g.0 == c.to_ascii_uppercase())
}

/// Width of `text` in glyph units.
pub fn width(text: &str) -> f32 {
    let w: f32 = text.chars().map(|c| glyph(c).map_or(SPACE, |g| g.1 + GAP)).sum();
    (w - GAP).max(0.0)
}

/// Extrudes `text` as round tubes in the XY plane, centered on the origin,
/// with the baseline at `y = 0`. `unit` is the size of one grid unit and
/// `radius` the stroke radius in world units.
pub fn extrude(m: &mut MeshBuilder, text: &str, unit: f32, radius: f32, sides: usize, c: Col) {
    let mut x = -width(text) * 0.5;
    for ch in text.chars() {
        let Some(g) = glyph(ch) else {
            x += SPACE;
            continue;
        };
        for stroke in g.2 {
            let path: Vec<(Vec3, f32)> = stroke
                .iter()
                .map(|&(px, py)| (Vec3::new((x + px) * unit, py * unit, 0.0), radius))
                .collect();
            if path.len() == 2 && path[0].0.distance(path[1].0) < unit * 0.2 {
                // A dot.
                m.ball(path[0].0, radius * 1.35, 1, c);
                continue;
            }
            m.tube(&path, sides, c, true);
            // Round the joints and ends.
            for p in &path {
                m.ball(p.0, radius, 0, c);
            }
        }
        x += g.1 + GAP;
    }
}
